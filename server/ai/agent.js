/**
 * Runs the Checkra AI Agent on a user inquiry and optional analysis context.
 *
 * @param {Object} input Request input containing { message, analysis, text, passage }
 * @returns {Promise<Object>} Structured agent outcome
 */
async function runCheckraAgent(input = {}) {
  const { message, analysis, text, passage } = input;

  // 1. Request validation
  if (!message || typeof message !== "string" || !message.trim()) {
    return {
      ok: false,
      error: "INVALID_REQUEST",
      message: "A non-empty user message string is required."
    };
  }

  // 2. Health & Provider Availability Check
  const health = await checkAiHealth();
  if (!health.ok || !health.available) {
    return {
      ok: false,
      error: "AI_UNAVAILABLE",
      message: "Checkra AI is temporarily unavailable. The deterministic Checkra analysis remains available."
    };
  }

  // 3. Tool Selection & Execution (Bounded)
  let totalToolCalls = 0;
  let webSearchCount = 0;
  let sourceRetrievalCount = 0;
  const toolsUsed = [];
  let toolDataPromptSection = "";
  let analysisToolResult = null;

  // A. If analysis is provided, invoke get_analysis_result tool
  if (analysis && typeof analysis === "object" && totalToolCalls < MAX_TOTAL_TOOLS) {
    analysisToolResult = executeTool("get_analysis_result", { analysis });
    toolsUsed.push("get_analysis_result");
    totalToolCalls++;

    if (analysisToolResult.available) {
      if (!analysisToolResult.hasScore) {
        toolDataPromptSection += `
[CHECKRA DETERMINISTIC ANALYSIS EVIDENCE (READ-ONLY)]
- Analysis ID: ${analysisToolResult.analysisId}
- Document Title: "${analysisToolResult.documentTitle}" (${analysisToolResult.wordCount} words)
- Similarity Score: UNAVAILABLE (No authoritative similarity score was provided)
- Exact Match Coverage: ${analysisToolResult.exactCoverage}%
- Near Match Coverage: ${analysisToolResult.nearCoverage}%
- Semantic Paraphrase Coverage: ${analysisToolResult.semanticCoverage}%
- Verified Sources Identified: ${analysisToolResult.verifiedSourcesCount}
- Total Matched Passages: ${analysisToolResult.matchedPassagesCount}
CRITICAL INSTRUCTION: The similarity score is unavailable for this document. You MUST explicitly state that the similarity score is unavailable. Do NOT assume, invent, or output 0% or any percentage score.
`;
      } else {
        toolDataPromptSection += `
[CHECKRA DETERMINISTIC ANALYSIS EVIDENCE (READ-ONLY)]
- Analysis ID: ${analysisToolResult.analysisId}
- Document Title: "${analysisToolResult.documentTitle}" (${analysisToolResult.wordCount} words)
- Overall Similarity Score: ${analysisToolResult.overallSimilarityScore}% (Grade ${analysisToolResult.grade}) [AUTHORITATIVE - IMMUTABLE]
- Exact Match Coverage: ${analysisToolResult.exactCoverage}%
- Near Match Coverage: ${analysisToolResult.nearCoverage}%
- Semantic Paraphrase Coverage: ${analysisToolResult.semanticCoverage}%
- Verified Sources Identified: ${analysisToolResult.verifiedSourcesCount}
- Total Matched Passages: ${analysisToolResult.matchedPassagesCount}
- Top Evidence Passages:
${analysisToolResult.topMatchedPassages.length > 0
  ? analysisToolResult.topMatchedPassages.map((p, i) => `  ${i + 1}. [${p.matchType} - ${p.similarityPercent}% match] "${p.passageText.substring(0, 160)}..."`).join("\n")
  : "  (No high-similarity passages detected)"}
- Mathematical Consistency Check: ${analysisToolResult.isMathematicallyConsistent ? "CONSISTENT" : "INCONSISTENT"}
${!analysisToolResult.isMathematicallyConsistent ? `- Inconsistency Notice: "${analysisToolResult.inconsistencyNotice}"` : ""}
CRITICAL INSTRUCTIONS:
1. The authoritative Checkra score is ${analysisToolResult.overallSimilarityScore}%. Do NOT calculate or derive a different score.
2. Do NOT attempt manual arithmetic on the component percentages. Do NOT say that components "add up" to another number.
3. ${!analysisToolResult.isMathematicallyConsistent
  ? `The component percentages do not reproduce the overall score. You MUST explicitly state: "${analysisToolResult.inconsistencyNotice}"`
  : "Explain what the exact, near, and semantic matches represent conceptually in the author's writing."}
`;
      }
    }
  }

  // B. If user asks for web research or supplies a passage to investigate
  const targetPassage = text || passage || (requiresWebResearch(message, input) ? message : null);
  if (targetPassage && requiresWebResearch(message, input) && totalToolCalls < MAX_TOTAL_TOOLS && webSearchCount < MAX_WEB_SEARCHES) {
    const searchTerms = targetPassage.split(/\s+/).slice(0, 8).join(" ");
    const searchRes = await executeTool("web_search", { query: searchTerms, maxResults: 3 });
    toolsUsed.push("web_search");
    totalToolCalls++;
    webSearchCount++;

    if (searchRes.ok && Array.isArray(searchRes.results) && searchRes.results.length > 0) {
      toolDataPromptSection += `\n[WEB SEARCH DISCOVERY RESULTS (CANDIDATES ONLY - NOT VERIFIED PROOF)]\n`;
      for (const cand of searchRes.results.slice(0, 2)) {
        if (totalToolCalls >= MAX_TOTAL_TOOLS || sourceRetrievalCount >= MAX_SOURCE_RETRIEVALS) break;
        const verifyRes = await executeTool("verify_source", {
          passage: targetPassage,
          url: cand.url,
          title: cand.title
        });
        toolsUsed.push("verify_source");
        totalToolCalls++;
        sourceRetrievalCount++;

        const simStr = verifyRes.sourceSimilarity ? `Source-Level Similarity: ${verifyRes.sourceSimilarity}` : "No Textual Overlap";
        toolDataPromptSection += `- Source: "${cand.title}" (${cand.url})\n  Status: ${verifyRes.status} | Match Classification: ${verifyRes.matchType} | ${simStr}\n  Evidence: ${verifyRes.evidence}\n`;
      }
    } else {
      toolDataPromptSection += `\n[WEB SEARCH RESULT]\nWeb search discovery returned no matching external candidate sources.\n`;
    }
  }

  // C. If user asks about AI writing detection or if aiWriting analysis is provided
  if ((requiresAiWritingDetection(message, input) || input.detectAiWriting) && totalToolCalls < MAX_TOTAL_TOOLS) {
    const aiText = text || passage || (analysis && (analysis.document?.text || analysis.text)) || (message.length > 30 ? message : null);
    if (aiText) {
      const aiResult = await executeTool("analyze_ai_writing", { text: aiText, options: input.options });
      toolsUsed.push("analyze_ai_writing");
      totalToolCalls++;

      if (aiResult.available && aiResult.aiWriting) {
        const w = aiResult.aiWriting;
        toolDataPromptSection += `
[CHECKRA AI WRITING STYLOMETRIC EVIDENCE (READ-ONLY)]
- Status: ${w.status}
- AI Writing Likelihood: ${w.likelihood !== null ? w.likelihood + "%" : "UNAVAILABLE (Insufficient text: < 50 words)"}
- Confidence: ${w.confidence}
- Signals Detected: ${w.signals?.length > 0 ? w.signals.join(", ") : "None detected"}
- Word Count: ${w.metrics?.wordCount || 0}
- Sentence Length CV: ${w.metrics?.sentenceLengthCV ?? "N/A"}
- Transition Density: ${w.metrics?.transitionDensity ?? "N/A"} per 100 words
- Limitations: ${w.limitations ? w.limitations.join(" ") : ""}
- Mandatory Disclaimer: "${w.disclaimer}"
CRITICAL INSTRUCTIONS:
1. AI Writing Likelihood is a probabilistic stylometric indicator, NOT a plagiarism score or similarity percentage.
2. NEVER describe AI Writing Likelihood as 'plagiarism percentage', 'similarity percentage', or 'copied percentage'.
3. Tone must be strictly objective and probabilistic; never claim certainty of authorship.
4. If likelihood is unavailable due to insufficient text (< 50 words), explain clearly that the text is too short (< 50 words) for reliable stylometric analysis.
`;
      }
    }
  }

  // D. If user requests a unified integrity report
  if (requiresIntegrityReport(message, input) && totalToolCalls < MAX_TOTAL_TOOLS) {
    const reportRes = executeTool("generate_integrity_report", {
      analysis,
      research: input.research,
      aiWriting: input.aiWriting || analysis?.aiWriting
    });
    if (reportRes.available && reportRes.report) {
      toolsUsed.push("generate_integrity_report");
      totalToolCalls++;
      const rep = reportRes.report;
      toolDataPromptSection += `
[CHECKRA UNIFIED INTEGRITY REPORT EVIDENCE (READ-ONLY)]
- Overall Similarity Score: ${rep.similarity.score !== null ? rep.similarity.score + "% (Grade " + rep.similarity.grade + ")" : "UNAVAILABLE"}
- AI-Writing Likelihood: ${rep.aiWriting.likelihood !== null ? rep.aiWriting.likelihood + "%" : "UNAVAILABLE"}
- Integrity Confidence: ${rep.integrityConfidence.level} (${rep.integrityConfidence.score}/100)
- Confidence Basis: ${rep.integrityConfidence.basis.join("; ")}
- Confidence Limitations: ${rep.integrityConfidence.limitations.join("; ")}
- Plagiarism-Relevant Evidence Count: ${rep.summary.plagiarismRelevantEvidenceCount}
- Contextual Source Count: ${rep.summary.contextualSourceCount}
CRITICAL INSTRUCTIONS:
1. Preserve absolute separation between Similarity Score and AI-Writing Likelihood.
2. Integrity Confidence represents evidence quality and completeness, NOT a probability of plagiarism or AI generation.
`;
    }
  }

  // E. If user requests writing quality / grammar improvement
  if (requiresWritingImprovement(message, input) && totalToolCalls < MAX_TOTAL_TOOLS) {
    const targetText = text || passage || (analysis && (analysis.document?.text || analysis.text)) || message;
    if (targetText) {
      const qualRes = executeTool("analyze_writing_quality", { text: targetText });
      if (qualRes.available && qualRes.quality) {
        toolsUsed.push("analyze_writing_quality");
        totalToolCalls++;
        const q = qualRes.quality;
        toolDataPromptSection += `
[CHECKRA WRITING QUALITY AUDIT EVIDENCE (READ-ONLY)]
- Status: ${q.status}
- Quality Score: ${q.qualityScore}/100
- Total Issues Detected: ${q.summary.total} (Grammar: ${q.summary.grammar}, Punctuation: ${q.summary.punctuation}, Wordiness: ${q.summary.wordiness}, Clarity: ${q.summary.clarity})
- Top Issues:
${q.issues.slice(0, 4).map(iss => `  - [${iss.type} - ${iss.severity}] "${iss.original}" -> Suggestion: "${iss.suggestion}" (${iss.explanation})`).join("\n") || "  (No mechanical or grammatical issues detected)"}
`;
      }
    }
  }

  // F. If user requests rewriting
  if (requiresRewrite(message, input) && totalToolCalls < MAX_TOTAL_TOOLS) {
    const targetText = text || passage || (analysis && (analysis.document?.text || analysis.text)) || null;
    if (targetText) {
      const mode = input.mode || (message.toLowerCase().includes("academic") ? "academic-readable" : (message.toLowerCase().includes("concise") ? "concise" : (message.toLowerCase().includes("professional") ? "professional" : (message.toLowerCase().includes("simple") ? "simple-english" : "clear-natural"))));
      const rewriteRes = await executeTool("rewrite_text", {
        text: targetText,
        mode,
        evidence: input.evidence,
        preserveCitations: input.preserveCitations !== false
      });
      if (rewriteRes.available && rewriteRes.rewrite) {
        toolsUsed.push("rewrite_text");
        totalToolCalls++;
        const rw = rewriteRes.rewrite;
        toolDataPromptSection += `
[CHECKRA REWRITE RESULT (READ-ONLY)]
- Mode: ${rw.modeName}
- Citation Status: ${rw.citationStatus}
- Evidence-Aware: ${rw.evidenceAware ? "YES (Flags " + rw.originalEvidenceClass + ")" : "NO"}
${rw.warning ? `- Warning: "${rw.warning}"` : ""}
- Rewritten Text:
"${rw.rewrittenText}"
`;
      }
    }
  }

  // G. If user requests claim extraction
  if (requiresClaimExtraction(message, input) && totalToolCalls < MAX_TOTAL_TOOLS) {
    const claimTargetText = text || passage || (analysis && (analysis.document?.text || analysis.text)) || message;
    if (claimTargetText) {
      const claimRes = executeTool("extract_claims", { text: claimTargetText });
      if (claimRes.available && Array.isArray(claimRes.claims)) {
        toolsUsed.push("extract_claims");
        totalToolCalls++;
        toolDataPromptSection += `
[CHECKRA CLAIM EXTRACTION EVIDENCE (READ-ONLY)]
- Total Claims Extracted: ${claimRes.stats?.totalClaims || 0}
- Statements Requiring Evidence: ${claimRes.stats?.requiresEvidenceCount || 0}
- Key Claims:
${claimRes.claims.slice(0, 4).map(c => `  - [${c.type} (Requires Evidence: ${c.requiresEvidence})] "${c.text}" (${c.reason})`).join("\n") || "  (No research claims identified)"}
`;
      }
    }
  }

  // H. If user requests citation analysis
  if (requiresCitationAnalysis(message, input) && totalToolCalls < MAX_TOTAL_TOOLS) {
    const citationTargetText = text || passage || (analysis && (analysis.document?.text || analysis.text)) || message;
    if (citationTargetText) {
      const citeRes = executeTool("analyze_citations", { text: citationTargetText });
      if (citeRes.available) {
        toolsUsed.push("analyze_citations");
        totalToolCalls++;
        toolDataPromptSection += `
[CHECKRA CITATION AUDIT EVIDENCE (READ-ONLY)]
- Total Citations Found: ${citeRes.stats?.totalCitations || 0} (Recognized: ${citeRes.stats?.recognized || 0}, Unrecognized: ${citeRes.stats?.unrecognized || 0})
- Possible Citation Gaps: ${citeRes.stats?.possibleGaps || 0}
- Citation Gaps:
${citeRes.citationGaps?.slice(0, 3).map(g => `  - [${g.claimType}] "${g.claimText}" -> ${g.recommendation}`).join("\n") || "  (No citation gaps detected)"}
`;
      }
    }
  }

  // I. If user requests research on a specific claim
  if (requiresResearchClaim(message, input) && totalToolCalls < MAX_TOTAL_TOOLS) {
    const targetClaim = input.claim || text || passage || message;
    if (targetClaim) {
      const researchRes = await executeTool("research_claim", {
        claim: targetClaim,
        context: input.context || "",
        options: input.options || {}
      });
      if (researchRes.available) {
        toolsUsed.push("research_claim");
        totalToolCalls++;
        toolDataPromptSection += `
[CHECKRA CLAIM RESEARCH EVIDENCE (READ-ONLY)]
- Claim: "${researchRes.claim}"
- Evidence Status: ${researchRes.status}
- Summary: ${researchRes.summary}
- Sources Evaluated: ${researchRes.sources?.length || 0}
${researchRes.sources?.slice(0, 2).map(s => `  - [${s.sourceType} - ${s.supportType}] "${s.title}" (${s.url})\n    Evidence: ${s.evidence}\n    Explanation: ${s.explanation}`).join("\n") || "  (No sources evaluated)"}
`;
      }
    }
  }

  // J. If user requests reference list generation
  if (requiresReferenceList(message, input) && totalToolCalls < MAX_TOTAL_TOOLS) {
    const sourcesToFormat = input.sources || input.verifiedSources || (analysis?.sources?.items) || [];
    const refRes = executeTool("generate_reference_list", {
      sources: sourcesToFormat,
      style: input.style || "APA"
    });
    if (refRes.available) {
      toolsUsed.push("generate_reference_list");
      totalToolCalls++;
      toolDataPromptSection += `
[CHECKRA REFERENCE LIST (READ-ONLY)]
- Style: ${refRes.style}
- Total References: ${refRes.totalReferences}
${refRes.references?.slice(0, 3).map(r => `  - ${r.formattedReference}`).join("\n") || "  (No verified source references to format)"}
`;
    }
  }

  if (!toolDataPromptSection) {
    toolDataPromptSection = `
[NOTE]
No Checkra document analysis was provided with this query. If the user asks about their score, document, or specific matches, clearly mention that no document analysis is currently loaded, and explain general writing integrity concepts.
`;
  }

  // 4. Construct Prompt
  const prompt = `${CHECKRA_SYSTEM_PROMPT}

${toolDataPromptSection}

[USER INQUIRY]
${message.trim()}

Respond strictly in the specified JSON format with keys: "summary", "findings", "evidence", "recommendations", "confidence".`;

  // 5. Generate completion via Model Abstraction
  const completion = await generateAiCompletion(prompt, { timeoutMs: 60000 });

  if (!completion.ok) {
    return {
      ok: false,
      error: completion.error || "AI_GENERATION_FAILED",
      message: "The AI agent was unable to complete reasoning for this request."
    };
  }

  // 6. Validate & Structure Model Output (with Score Protection Enforcement)
  const structuredResponse = parseAndValidateModelOutput(completion.response, analysisToolResult);

  return {
    ok: true,
    agent: {
      provider: completion.provider || getAiConfig().provider,
      model: completion.model || getAiConfig().model
    },
    response: structuredResponse,
    toolsUsed
  };
}

/**
 * Dedicated Web Research and Source Verification Workflow (POST /api/agent/research)
 *
 * @param {Object} input Request containing { query, text, analysis, analysisId }
 * @returns {Promise<Object>} Structured verification response
 */
async function runCheckraResearch(input = {}) {
  const { query, text, analysis, analysisId } = input;

  // 1. Strict Request Validation
  if (!query || typeof query !== "string" || !query.trim()) {
    return {
      ok: false,
      error: "INVALID_REQUEST",
      message: "A non-empty query string is required."
    };
  }

  if (!text || typeof text !== "string" || !text.trim()) {
    return {
      ok: false,
      error: "INVALID_REQUEST",
      message: "A non-empty passage text string is required for source verification."
    };
  }

  const cleanQuery = query.trim();
  const cleanPassage = text.trim();

  // 2. Resolve Authoritative Checkra Score (Strictly from deterministic engine or session store)
  let authoritativeScore = null;
  let scoreStatus = "UNAVAILABLE";
  let grade = null;

  let targetAnalysis = analysis || null;
  if (!targetAnalysis && analysisId) {
    targetAnalysis = db.getSessionAnalysis(analysisId);
  }

  if (targetAnalysis && typeof targetAnalysis === "object") {
    const sim = targetAnalysis.similarity || {};
    if (typeof sim.score === "number" && !isNaN(sim.score)) {
      authoritativeScore = sim.score;
      scoreStatus = "AVAILABLE";
      grade = sim.grade || null;
    }
  }

  // Bounded Tool Call Counters (Step 9)
  let totalToolCalls = 0;
  let webSearchCalls = 0;
  let sourceRetrievalCalls = 0;
  const toolsUsed = [];

  // 3. Discover Candidate Web Sources via Search Tool
  if (totalToolCalls >= MAX_TOTAL_TOOLS || webSearchCalls >= MAX_WEB_SEARCHES) {
    return {
      ok: false,
      status: "LIMIT_EXCEEDED",
      message: "Maximum tool limits reached."
    };
  }

  // Construct search query from query or passage
  const searchQuery = cleanQuery.length >= 10 && !cleanQuery.endsWith("?")
    ? cleanQuery
    : cleanPassage.split(/\s+/).slice(0, 10).join(" ");

  const searchResult = await executeTool("web_search", { query: searchQuery, maxResults: 5 });
  toolsUsed.push("web_search");
  totalToolCalls++;
  webSearchCalls++;

  // Step 12: Search failure behavior
  if (!searchResult.ok || !Array.isArray(searchResult.results) || searchResult.results.length === 0) {
    return {
      ok: false,
      status: "SEARCH_UNAVAILABLE",
      message: "Web search is temporarily unavailable."
    };
  }

  // 4. Retrieve and Verify Each Candidate Source
  const candidateResults = searchResult.results;
  const verifiedSources = [];

  for (const candidate of candidateResults) {
    if (totalToolCalls >= MAX_TOTAL_TOOLS || sourceRetrievalCalls >= MAX_SOURCE_RETRIEVALS) {
      break;
    }

    const verification = await executeTool("verify_source", {
      passage: cleanPassage,
      url: candidate.url,
      title: candidate.title
    });

    toolsUsed.push("verify_source");
    totalToolCalls++;
    sourceRetrievalCalls++;

    verifiedSources.push({
      url: candidate.url,
      title: verification.title || candidate.title || extractDomain(candidate.url),
      domain: verification.domain || extractDomain(candidate.url),
      status: verification.status || "SOURCE_NOT_VERIFIABLE",
      matchType: verification.matchType || "NO_MATCH",
      sourceSimilarity: verification.sourceSimilarity || null, // null for TOPICAL, CONCEPTUAL, NO_MATCH
      similarity: verification.sourceSimilarity || null, // Backwards-compatible alias
      evidence: verification.evidence || (verification.status === "SOURCE_NOT_VERIFIABLE" ? `Source retrieval failed: ${verification.reason}` : "No evidence detected.")
    });
  }

  // 5. Synthesize AI Explanation with Qwen3 1.7B
  let aiExplanation = null;
  const health = await checkAiHealth();

  if (health.ok && health.available) {
    const verifiedList = verifiedSources.map((s, i) =>
      `${i + 1}. [Status: ${s.status} | Match Classification: ${s.matchType} | Source-Level Similarity: ${s.sourceSimilarity || "None (No Textual Overlap)"}] "${s.title}" (${s.url})\n   Evidence: ${s.evidence}`
    ).join("\n\n");

    const prompt = `${CHECKRA_SYSTEM_PROMPT}

[INVESTIGATED PASSAGE]
"${cleanPassage}"

[DETERMINISTIC WEB SOURCE VERIFICATION EVIDENCE (READ-ONLY)]
${verifiedList}

[AUTHORITATIVE CHECKRA SIMILARITY SCORE]
${scoreStatus === "AVAILABLE" ? `${authoritativeScore}% (Grade ${grade}) [IMMUTABLE]` : "UNAVAILABLE — No authoritative Checkra document analysis was supplied for this inquiry."}

[USER RESEARCH QUERY]
${cleanQuery}

Respond strictly in the specified JSON format with keys: "summary", "findings", "evidence", "recommendations", "confidence".
CRITICAL RULES (Phase 3.1 Score Semantics):
1. AUTHORITATIVE SCORE IS IMMUTABLE: If Authoritative Score is UNAVAILABLE, you MUST NOT state, calculate, or invent an overall similarity score or plagiarism percentage.
2. TOPICAL_SIMILARITY: The source is topically related, but no textual overlap was verified. This is NOT plagiarism. Never state a percentage for topical similarity.
3. CONCEPTUAL_SIMILARITY: The source discusses related concepts, but this does not by itself establish plagiarism. Never state a percentage for conceptual similarity.
4. EXACT_MATCH / NEAR_MATCH: The retrieved source contains an exact/near textual match.
5. STRONG_PARAPHRASE / POSSIBLE_PARAPHRASE: The retrieved source contains evidence of possible/strong paraphrased overlap.
6. Clearly distinguish between sources that have confirmed text overlap versus those that are only topically related.`;

    const completion = await generateAiCompletion(prompt, { timeoutMs: 30000 });
    if (completion.ok) {
      aiExplanation = parseAndValidateModelOutput(completion.response);
    }
  }

  const rawSummary = aiExplanation ? aiExplanation.summary : "Source verification completed via deterministic comparison engines.";
  const rawFindings = aiExplanation ? aiExplanation.findings : [];

  const sanitizedExplanation = sanitizeResearchExplanation(rawSummary, authoritativeScore, verifiedSources);
  const sanitizedFindings = sanitizeResearchFindings(rawFindings, authoritativeScore, verifiedSources);

  return {
    ok: true,
    query: cleanQuery,
    text: cleanPassage,
    authoritativeScore,
    scoreStatus,
    sources: verifiedSources,
    explanation: sanitizedExplanation,
    findings: sanitizedFindings,
    evidence: aiExplanation ? aiExplanation.evidence : [],
    agent: {
      provider: getAiConfig().provider,
      model: getAiConfig().model
    },
    toolsUsed
  };
}

