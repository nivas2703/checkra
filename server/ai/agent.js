/**
 * Checkra AI Agent — Core Orchestrator
 *
 * Implements the reasoning and tool orchestration layer above Checkra:
 * 1. Understands user inquiry
 * 2. Selects and executes internal Checkra evidence tools
 * 3. Observes tool results without mutating deterministic scores
 * 4. Synthesizes structured, defensible advice via Qwen3 1.7B
 *
 * Safeguards:
 * - Authoritative score immutability (scores are strictly read-only)
 * - Inconsistency disclosure (flags discrepancies when components deviate from overall score)
 * - Missing score protection (never assumes or fabricates 0% when score is absent)
 * - Bounded tool calls (Max 3)
 * - Safe JSON fallback parsing (never crashes server)
 * - Graceful degradation when AI provider is offline
 */

const { checkAiHealth, generateAiCompletion, getAiConfig } = require("./model");
const { CHECKRA_SYSTEM_PROMPT } = require("./prompts");
const { executeTool } = require("./tools");

/**
 * Attempts to parse and validate the model's response as the required JSON schema,
 * enforcing score immutability, missing-score honesty, and inconsistency disclaimers.
 *
 * @param {string} rawText Raw text generated by the AI model
 * @param {Object} [analysisToolResult] Tool output containing authoritative scores
 * @returns {Object} Validated structured object
 */
function parseAndValidateModelOutput(rawText, analysisToolResult = null) {
  if (!rawText || typeof rawText !== "string") {
    return {
      summary: "No response was generated by the reasoning assistant.",
      findings: [],
      evidence: [],
      recommendations: [],
      confidence: "low",
      structured: false
    };
  }

  // Strip markdown code fences if present (e.g. ```json ... ```)
  let cleaned = rawText.trim();
  if (cleaned.startsWith("```")) {
    cleaned = cleaned.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "").trim();
  }

  // Try extracting the first valid JSON block if surrounded by extraneous text
  const firstBrace = cleaned.indexOf("{");
  const lastBrace = cleaned.lastIndexOf("}");
  if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
    cleaned = cleaned.substring(firstBrace, lastBrace + 1);
  }

  let structured = false;
  let summary = "";
  let findings = [];
  let evidence = [];
  let recommendations = [];
  let confidence = "medium";

  try {
    const parsed = JSON.parse(cleaned);
    summary = typeof parsed.summary === "string" && parsed.summary.trim()
      ? parsed.summary.trim()
      : (typeof parsed.explanation === "string" ? parsed.explanation.trim() : rawText.trim());

    findings = Array.isArray(parsed.findings)
      ? parsed.findings.map(f => String(f).trim()).filter(Boolean)
      : [];

    evidence = Array.isArray(parsed.evidence)
      ? parsed.evidence.map(e => String(e).trim()).filter(Boolean)
      : [];

    recommendations = Array.isArray(parsed.recommendations)
      ? parsed.recommendations.map(r => String(r).trim()).filter(Boolean)
      : [];

    const validConfidences = ["high", "medium", "low"];
    if (typeof parsed.confidence === "string" && validConfidences.includes(parsed.confidence.toLowerCase())) {
      confidence = parsed.confidence.toLowerCase();
    }
    structured = true;
  } catch (err) {
    summary = rawText.trim();
    structured = false;
  }

  // ENFORCE SCORE EXPLANATION INTEGRITY RULES
  if (analysisToolResult && analysisToolResult.available) {
    // Rule D: Missing score produces a clear "score unavailable" response
    if (!analysisToolResult.hasScore) {
      const unavailableMsg = "The similarity score is unavailable for this document; no authoritative score was calculated in the provided analysis result.";
      if (!summary.toLowerCase().includes("unavailable")) {
        summary = `${unavailableMsg} ${summary}`;
      }
      if (!findings.some(f => f.toLowerCase().includes("unavailable"))) {
        findings.unshift("Score Unavailable: The analysis context does not contain a verified similarity score.");
      }
    } else {
      const authScore = analysisToolResult.overallSimilarityScore;

      // Rule 6 & Rule C: If mathematical values appear inconsistent, enforce the required disclaimer
      if (!analysisToolResult.isMathematicallyConsistent && analysisToolResult.inconsistencyNotice) {
        const notice = analysisToolResult.inconsistencyNotice;
        const alreadyHasNotice = summary.includes("do not independently reproduce") ||
          findings.some(f => f.includes("do not independently reproduce"));

        if (!alreadyHasNotice) {
          summary = `${summary} ${notice}`;
          findings.unshift(notice);
        }
      }

      // Rule 1 & Rule B: Authoritative score must be preserved; never let LLM hallucinate a different score
      // If the summary contains a fabricated different overall score percentage, note the authoritative score
      if (!summary.includes(`${authScore}%`)) {
        findings.unshift(`Authoritative Checkra Overall Score: ${authScore}% (immutable).`);
      }
    }
  }

  return {
    summary,
    findings,
    evidence,
    recommendations,
    confidence,
    structured
  };
}

/**
 * Runs the Checkra AI Agent on a user inquiry and optional analysis context.
 *
 * @param {Object} input Request input containing { message, analysis }
 * @returns {Promise<Object>} Structured agent outcome
 */
async function runCheckraAgent(input = {}) {
  const { message, analysis } = input;

  // 1. Request validation
  if (!message || typeof message !== "string" || !message.trim()) {
    return {
      ok: false,
      error: "INVALID_REQUEST",
      message: "A non-empty user message string is required."
    };
  }

  // 2. Health & Provider Availability Check
  const health = await checkAiHealth();
  if (!health.ok || !health.available) {
    return {
      ok: false,
      error: "AI_UNAVAILABLE",
      message: "Checkra AI is temporarily unavailable. The deterministic Checkra analysis remains available."
    };
  }

  // 3. Tool Selection & Execution (Bounded)
  const toolsUsed = [];
  let toolDataPromptSection = "";
  let analysisToolResult = null;

  // If analysis is provided, invoke get_analysis_result tool
  if (analysis && typeof analysis === "object") {
    analysisToolResult = executeTool("get_analysis_result", { analysis });
    toolsUsed.push("get_analysis_result");

    if (analysisToolResult.available) {
      if (!analysisToolResult.hasScore) {
        toolDataPromptSection = `
[CHECKRA DETERMINISTIC ANALYSIS EVIDENCE (READ-ONLY)]
- Analysis ID: ${analysisToolResult.analysisId}
- Document Title: "${analysisToolResult.documentTitle}" (${analysisToolResult.wordCount} words)
- Similarity Score: UNAVAILABLE (No authoritative similarity score was provided)
- Exact Match Coverage: ${analysisToolResult.exactCoverage}%
- Near Match Coverage: ${analysisToolResult.nearCoverage}%
- Semantic Paraphrase Coverage: ${analysisToolResult.semanticCoverage}%
- Verified Sources Identified: ${analysisToolResult.verifiedSourcesCount}
- Total Matched Passages: ${analysisToolResult.matchedPassagesCount}
CRITICAL INSTRUCTION: The similarity score is unavailable for this document. You MUST explicitly state that the similarity score is unavailable. Do NOT assume, invent, or output 0% or any percentage score.
`;
      } else {
        toolDataPromptSection = `
[CHECKRA DETERMINISTIC ANALYSIS EVIDENCE (READ-ONLY)]
- Analysis ID: ${analysisToolResult.analysisId}
- Document Title: "${analysisToolResult.documentTitle}" (${analysisToolResult.wordCount} words)
- Overall Similarity Score: ${analysisToolResult.overallSimilarityScore}% (Grade ${analysisToolResult.grade}) [AUTHORITATIVE - IMMUTABLE]
- Exact Match Coverage: ${analysisToolResult.exactCoverage}%
- Near Match Coverage: ${analysisToolResult.nearCoverage}%
- Semantic Paraphrase Coverage: ${analysisToolResult.semanticCoverage}%
- Verified Sources Identified: ${analysisToolResult.verifiedSourcesCount}
- Total Matched Passages: ${analysisToolResult.matchedPassagesCount}
- Top Evidence Passages:
${analysisToolResult.topMatchedPassages.length > 0
  ? analysisToolResult.topMatchedPassages.map((p, i) => `  ${i + 1}. [${p.matchType} - ${p.similarityPercent}% match] "${p.passageText.substring(0, 160)}..."`).join("\n")
  : "  (No high-similarity passages detected)"}
- Mathematical Consistency Check: ${analysisToolResult.isMathematicallyConsistent ? "CONSISTENT" : "INCONSISTENT"}
${!analysisToolResult.isMathematicallyConsistent ? `- Inconsistency Notice: "${analysisToolResult.inconsistencyNotice}"` : ""}
CRITICAL INSTRUCTIONS:
1. The authoritative Checkra score is ${analysisToolResult.overallSimilarityScore}%. Do NOT calculate or derive a different score.
2. Do NOT attempt manual arithmetic on the component percentages. Do NOT say that components "add up" to another number.
3. ${!analysisToolResult.isMathematicallyConsistent
  ? `The component percentages do not reproduce the overall score. You MUST explicitly state: "${analysisToolResult.inconsistencyNotice}"`
  : "Explain what the exact, near, and semantic matches represent conceptually in the author's writing."}
`;
      }
    }
  } else {
    toolDataPromptSection = `
[NOTE]
No Checkra document analysis was provided with this query. If the user asks about their score, document, or specific matches, clearly mention that no document analysis is currently loaded, and explain general writing integrity concepts.
`;
  }

  // 4. Construct Prompt
  const prompt = `${CHECKRA_SYSTEM_PROMPT}

${toolDataPromptSection}

[USER INQUIRY]
${message.trim()}

Respond strictly in the specified JSON format with keys: "summary", "findings", "evidence", "recommendations", "confidence".`;

  // 5. Generate completion via Model Abstraction
  const completion = await generateAiCompletion(prompt, { timeoutMs: 60000 });

  if (!completion.ok) {
    return {
      ok: false,
      error: completion.error || "AI_GENERATION_FAILED",
      message: "The AI agent was unable to complete reasoning for this request."
    };
  }

  // 6. Validate & Structure Model Output (with Score Protection Enforcement)
  const structuredResponse = parseAndValidateModelOutput(completion.response, analysisToolResult);

  return {
    ok: true,
    agent: {
      provider: completion.provider || getAiConfig().provider,
      model: completion.model || getAiConfig().model
    },
    response: structuredResponse,
    toolsUsed
  };
}

module.exports = {
  runCheckraAgent,
  parseAndValidateModelOutput
};
