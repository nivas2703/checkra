/**
 * Attempts to parse and validate the model's response as the required JSON schema,
 * enforcing score immutability, missing-score honesty, and inconsistency disclaimers.
 *
 * @param {string} rawText Raw text generated by the AI model
 * @param {Object} [analysisToolResult] Tool output containing authoritative scores
 * @returns {Object} Validated structured object
 */
function parseAndValidateModelOutput(rawText, analysisToolResult = null) {
  if (!rawText || typeof rawText !== "string") {
    return {
      summary: "No response was generated by the reasoning assistant.",
      findings: [],
      evidence: [],
      recommendations: [],
      confidence: "low",
      structured: false
    };
  }

  // Strip markdown code fences if present (e.g. ```json ... ```)
  let cleaned = rawText.trim();
  if (cleaned.startsWith("```")) {
    cleaned = cleaned.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "").trim();
  }

  // Try extracting the first valid JSON block if surrounded by extraneous text
  const firstBrace = cleaned.indexOf("{");
  const lastBrace = cleaned.lastIndexOf("}");
  if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
    cleaned = cleaned.substring(firstBrace, lastBrace + 1);
  }

  let structured = false;
  let summary = "";
  let findings = [];
  let evidence = [];
  let recommendations = [];
  let confidence = "medium";

  try {
    const parsed = JSON.parse(cleaned);
    summary = typeof parsed.summary === "string" && parsed.summary.trim()
      ? parsed.summary.trim()
      : (typeof parsed.explanation === "string" ? parsed.explanation.trim() : rawText.trim());

    findings = Array.isArray(parsed.findings)
      ? parsed.findings.map(f => String(f).trim()).filter(Boolean)
      : [];

    evidence = Array.isArray(parsed.evidence)
      ? parsed.evidence.map(e => String(e).trim()).filter(Boolean)
      : [];

    recommendations = Array.isArray(parsed.recommendations)
      ? parsed.recommendations.map(r => String(r).trim()).filter(Boolean)
      : [];

    const validConfidences = ["high", "medium", "low"];
    if (typeof parsed.confidence === "string" && validConfidences.includes(parsed.confidence.toLowerCase())) {
      confidence = parsed.confidence.toLowerCase();
    }
    structured = true;
  } catch (err) {
    summary = rawText.trim();
    structured = false;
  }

  // ENFORCE SCORE EXPLANATION INTEGRITY RULES
  if (analysisToolResult && analysisToolResult.available) {
    // Rule D: Missing score produces a clear "score unavailable" response
    if (!analysisToolResult.hasScore) {
      const unavailableMsg = "The similarity score is unavailable for this document; no authoritative score was calculated in the provided analysis result.";
      if (!summary.toLowerCase().includes("unavailable")) {
        summary = `${unavailableMsg} ${summary}`;
      }
      if (!findings.some(f => f.toLowerCase().includes("unavailable"))) {
        findings.unshift("Score Unavailable: The analysis context does not contain a verified similarity score.");
      }
    } else {
      const authScore = analysisToolResult.overallSimilarityScore;

      // Rule 6 & Rule C: If mathematical values appear inconsistent, enforce the required disclaimer
      if (!analysisToolResult.isMathematicallyConsistent && analysisToolResult.inconsistencyNotice) {
        const notice = analysisToolResult.inconsistencyNotice;
        const alreadyHasNotice = summary.includes("do not independently reproduce") ||
          findings.some(f => f.includes("do not independently reproduce"));

        if (!alreadyHasNotice) {
          summary = `${summary} ${notice}`;
          findings.unshift(notice);
        }
      }

      // Rule 1 & Rule B: Authoritative score must be preserved; never let LLM hallucinate a different score
      if (!summary.includes(`${authScore}%`)) {
        findings.unshift(`Authoritative Checkra Overall Score: ${authScore}% (immutable).`);
      }
    }
  }

  return {
    summary,
    findings,
    evidence,
    recommendations,
    confidence,
    structured
  };
}

/**
 * Sanitizes LLM research explanations to guarantee that topical or conceptual similarity
 * is never represented as an overall plagiarism or similarity percentage.
 *
 * @param {string} explanation
 * @param {number|null} authoritativeScore
 * @param {Array} sources
 * @returns {string}
 */
function sanitizeResearchExplanation(explanation, authoritativeScore, sources = []) {
  if (!explanation || typeof explanation !== "string") return explanation;

  let sanitized = explanation;

  if (authoritativeScore === null) {
    // Prohibit hallucinating an overall score when no authoritative score was supplied
    sanitized = sanitized
      .replace(/(?:the\s+)?(?:overall\s+)?(?:similarity|plagiarism)\s+score\s+is\s+\d+%/gi, "no authoritative similarity score was provided")
      .replace(/(?:with\s+a\s+)?(?:similarity|plagiarism)\s+score\s+of\s+\d+%/gi, "with no textual match")
      .replace(/overall\s+(?:similarity|plagiarism)\s+(?:of\s+)?\d+%/gi, "topical similarity without textual overlap");
  }

  // Ensure topical similarity is not mischaracterized as verified plagiarism
  const hasTextualMatch = sources.some(s => s.matchType === "EXACT_MATCH" || s.matchType === "NEAR_MATCH" || s.matchType === "STRONG_PARAPHRASE");
  if (!hasTextualMatch) {
    if (sanitized.includes("verified") && !sanitized.includes("not plagiarism") && !sanitized.includes("no textual")) {
      sanitized = sanitized.replace(/is verified/gi, "is topically related, but no textual overlap was verified");
    }
  }

  return sanitized.trim();
}

/**
 * Sanitizes LLM research findings array
 * @param {Array} findings
 * @param {number|null} authoritativeScore
 * @param {Array} sources
 * @returns {Array}
 */
function sanitizeResearchFindings(findings = [], authoritativeScore, sources = []) {
  if (!Array.isArray(findings)) return [];
  const hasTextualMatch = sources.some(s => s.matchType === "EXACT_MATCH" || s.matchType === "NEAR_MATCH" || s.matchType === "STRONG_PARAPHRASE");

  return findings.map(f => {
    let clean = String(f);
    if (authoritativeScore === null) {
      clean = clean
        .replace(/(?:the\s+)?(?:overall\s+)?(?:similarity|plagiarism)\s+score\s+is\s+\d+%/gi, "no authoritative similarity score was provided")
        .replace(/(?:with\s+a\s+)?(?:similarity|plagiarism)\s+score\s+of\s+\d+%/gi, "with no textual match");
    }
    if (!hasTextualMatch && clean.includes("is verified") && !clean.includes("not plagiarism")) {
      clean = clean.replace(/is verified/gi, "is topically related, but no textual overlap was verified");
    }
    return clean;
  });
}

